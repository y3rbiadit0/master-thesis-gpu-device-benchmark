"""Checks for the MoE import's label parsing and archive separation."""

import csv
import importlib.util
import json
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def load(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / "tools" / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


moe = load("import_moe_evidence")
evidence = load("rebuild_main_evidence")


class MoeImportTests(unittest.TestCase):
    def test_routing_and_hidden_size_are_separated(self):
        self.assertEqual(moe.split_case("locality80,hidden=256"), ("locality80", 256))

    def test_unknown_routing_label_is_rejected(self):
        for label in ("skewed,hidden=256", "uniform", "uniform,hidden=big"):
            with self.subTest(label=label), self.assertRaises(ValueError):
                moe.split_case(label)

    def test_topology_label_gives_rank_count(self):
        self.assertEqual([moe.ranks_of(t) for t in ("1n1g", "2n1g", "1n4g", "8n4g")], [1, 2, 4, 32])

    def test_generated_table_names_the_tool_that_wrote_it(self):
        block = evidence.render_table("lr", ["Stack", "Latency"], [r"MPI & 1\\"],
                                      generator="tools/import_moe_evidence.py")
        self.assertIn("% Generated by tools/import_moe_evidence.py;", block)

    def test_moe_is_archived_apart_from_the_reconciled_summary(self):
        with (ROOT / "data/main-campaign/benchmark-summary.csv").open(newline="") as stream:
            benchmarks = {row["benchmark"] for row in csv.DictReader(stream)}
        self.assertNotIn("moe", benchmarks)
        manifest = json.loads((ROOT / "data/main-campaign/moe-manifest.json").read_text())
        self.assertEqual(len(manifest["sources"]), 1)

    def test_exported_moe_matrix_is_complete_at_the_declared_repetition_count(self):
        with (ROOT / "data/main-campaign/moe-summary.csv").open(newline="") as stream:
            rows = list(csv.DictReader(stream))
        self.assertEqual(len(rows), len(moe.TOPOLOGIES) * len(moe.ROUTINGS) * len(moe.BACKENDS))
        self.assertEqual({row["n_jobs"] for row in rows}, {"5"})
        self.assertEqual({row["n_trials"] for row in rows}, {"15"})


if __name__ == "__main__":
    unittest.main()
